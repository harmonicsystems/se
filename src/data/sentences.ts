export function getSentencesByDifficulty(difficulty: 'beginner' | 'intermediate' | 'advanced'): SpeakingSentence[] {
  return speakingSentences.filter((s) => s.difficulty === difficulty);
}

export function getRandomSentences(count: number, difficulty?: 'beginner' | 'intermediate' | 'advanced'): SpeakingSentence[] {
  const source = difficulty ? getSentencesByDifficulty(difficulty) : speakingSentences;
  const shuffled = [...source].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
