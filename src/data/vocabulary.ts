export function getVocabularyByCategory(category: Category): VocabularyItem[] {
  return vocabulary.filter((item) => item.category === category);
}

export function getRandomVocabulary(count: number, category?: Category): VocabularyItem[] {
  const source = category ? getVocabularyByCategory(category) : vocabulary;
  const shuffled = [...source].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
